/* ══════════════════════════════════════════════════════════════
 * sensor_task
 * Baca XY-MD02 setiap 5 detik, kirim ke queue
 * ══════════════════════════════════════════════════════════════ */
void sensor_task(void *arg)
{
    sensor_data_t data;
    sensor_init();

    while (1)
    {
        int ret = sensor_read(&data);

        if (ret == SENSOR_OK)
        {
            /* Overwrite queue dengan data terbaru */
            osMessageQueuePut(sensor_queue, &data, 0, 0);
        }
        /* Debug via USART1 */
        char dbg[64];
                snprintf(dbg, sizeof(dbg),
                         "[SENSOR] ret=%d T=%.1f H=%.1f\r\n",
                         ret, data.temperature, data.humidity);
                HAL_UART_Transmit(&huart1, (uint8_t*)dbg, strlen(dbg), 100);

        osDelay(5000);
    }
}

/* ══════════════════════════════════════════════════════════════
 * display_task
 * Update ST7920 setiap 500ms dengan data terbaru dari queue
 * ══════════════════════════════════════════════════════════════ */
void display_task(void *arg)
{
    sensor_data_t data = {0};
    char buf[32];

    ST7920_Init();

    while (1)
    {
        /* Ambil data dari queue, non-blocking */
        osMessageQueueGet(sensor_queue, &data, NULL, 0);

        ST7920_ClearBuffer();

        /* ── Header ── */
        ST7920_DrawStr(0, 0, "STM32 Monitor");
        ST7920_DrawHLine(0, 10, 128, 1);

        /* ── Sensor data ── */
        if (data.valid)
        {
            snprintf(buf, sizeof(buf), "Temp : %.1f C", data.temperature);
            ST7920_DrawStr(0, 14, buf);

            snprintf(buf, sizeof(buf), "Humi : %.1f %%", data.humidity);
            ST7920_DrawStr(0, 26, buf);
        }
        else
        {
            ST7920_DrawStr(0, 14, "Sensor: waiting..");
        }

        /* ── LTE status (placeholder) ── */
        ST7920_DrawHLine(0, 40, 128, 1);
        ST7920_DrawStr(0, 44, "LTE : --");
        ST7920_DrawStr(0, 54, "MQTT: --");

        ST7920_SendBuffer();

        osDelay(500);
    }
}


